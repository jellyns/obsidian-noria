import fs from "node:fs";
import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const runtimeRoot = path.join(root, "src", "runtime");
const outFile = path.join(root, "src", "generated", "embedded-runtime-sources.js");

const includeRoots = ["views", "core", "config"];
const allowedExt = new Set([".js", ".css", ".md", ".json", ".xml"]);
const skipParts = new Set(["node_modules", ".git", "dist", "build", "coverage"]);
const retiredEmbeddedKeys = new Set([
  "views/tasks-timeline/view.js"
]);

function toEmbeddedKey(file) {
  return path.relative(runtimeRoot, file).replace(/\\/g, "/");
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (skipParts.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, out);
      continue;
    }
    if (!entry.isFile()) continue;
    if (!allowedExt.has(path.extname(entry.name).toLowerCase())) continue;
    out.push(full);
  }
  return out;
}

const files = includeRoots
  .flatMap((dir) => walk(path.join(runtimeRoot, dir)))
  .filter((file) => !retiredEmbeddedKeys.has(toEmbeddedKey(file)))
  .sort((a, b) => toEmbeddedKey(a).localeCompare(toEmbeddedKey(b)));

const sourceRecords = files.map((file) => {
  const key = toEmbeddedKey(file);
  const content = fs.readFileSync(file, "utf8");
  return { key, content };
});

const buildHash = crypto.createHash("sha256");
for (const record of sourceRecords) {
  buildHash.update(record.key);
  buildHash.update("\0");
  buildHash.update(record.content);
  buildHash.update("\0");
}
const runtimeBuildId = buildHash.digest("hex").slice(0, 16);

const entries = sourceRecords.map(({ key, content }) => {
  return `  ${JSON.stringify(key)}: ${JSON.stringify(content)}`;
});

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  [
    '"use strict";',
    "",
    "// Generated by scripts/build-embedded-runtime.mjs. Do not edit by hand.",
    "const NORIA_EMBEDDED_SOURCES = Object.freeze({",
    entries.join(",\n"),
    "});",
    "",
    `const NORIA_RUNTIME_BUILD_ID = ${JSON.stringify(runtimeBuildId)};`,
    "",
    "module.exports = { NORIA_EMBEDDED_SOURCES, NORIA_RUNTIME_BUILD_ID };",
    ""
  ].join("\n"),
  "utf8"
);

console.log(`embedded ${files.length} runtime files into ${path.relative(root, outFile).replace(/\\/g, "/")} (${runtimeBuildId})`);
