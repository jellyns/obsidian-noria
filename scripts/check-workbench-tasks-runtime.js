// Run in Obsidian's NoriaTest renderer after installing the current build.
(async()=>{
  if(app.vault.getName()!=="NoriaTest")throw new Error("Use the isolated vault");
  const p=app.plugins.plugins.noria,fs=require("fs"),root="F:/NoriaTest/_acceptance-c-tasks-20260914";
  const fixture=p.getManagedPath("projectsRoot")+"/C字段验收",path=fixture+"/任务.md";
  const report=[];
  const check=(name,ok)=>{report.push({name,ok:!!ok});fs.writeFileSync(root+"/runtime-results.json",JSON.stringify(report,null,2));if(!ok)throw new Error(name);};
  const wait=async predicate=>{for(let i=0;i<100;i++){if(await predicate())return;await new Promise(r=>setTimeout(r,40));}throw new Error("condition timed out");};
  if(!app.vault.getAbstractFileByPath(fixture))await app.vault.createFolder(fixture);
  const source="---\ntest_fixture: true\n---\n\n## 任务\n\n- [ ] 整理周末散步路线 #生活 [custom:: 保留] ^walk  \n- [ ] 选出六张街景照片 [due:: 2099-01-10]\n\n# 留下的记录\n这段原文保留。  \n";
  if(app.vault.getAbstractFileByPath(path))throw new Error("Test fixture already exists; inspect before rerunning");
  await app.vault.create(path,source);
  fs.writeFileSync(root+"/fixture-source.md",source);
  const text=()=>p.loadTextFromVault(path);
  const task=async needle=>{const raw=(await text()).split("\n").find(line=>line.includes(needle)&&line.startsWith("- ["));if(!raw)throw new Error("task missing: "+needle);return {path,text:raw,rawText:raw,line:(await text()).split("\n").indexOf(raw)};};
  const overlay=()=>[...document.querySelectorAll(".tc-planner-te-overlay--workbench")].find(el=>el.dataset.sourcePath===path);
  const field=id=>overlay()?.querySelector("#tc-planner-te-"+id);
  const open=async needle=>{await p.openTaskDetails(await task(needle));await wait(overlay);};
  const close=()=>overlay()?.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}));
  const save=async()=>{overlay().querySelector(".tc-planner-te-btn--primary").click();await wait(()=>!overlay());};
  const q=window.__noriaC={p,root,path,fixture,report,check,wait,task,open,overlay,field,close,save,text};
  await open("散步路线");
  check("Undated fields stay empty",["start-date","start-time","end-date","end-time","scheduled-date"].every(id=>field(id).value===""));
  check("Compact title preserves metadata separately",field("title").value==="整理周末散步路线");
  field("title").value="整理两条周末散步路线";
  overlay().dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",ctrlKey:true,isComposing:true,bubbles:true}));
  check("IME confirmation does not submit",!!overlay()&&(await text())===source);
  await save();
  check("Title-only save preserves source and empty dates",(await text())===source.replace("整理周末散步路线","整理两条周末散步路线"));
  await open("散步路线");field("title").value="保留尚未提交的改写";close();
  await open("散步路线");check("Escape retains task draft",field("title").value==="保留尚未提交的改写");
  overlay().querySelector(".tc-planner-te-discard").click();
  await open("散步路线");check("Explicit cancel discards just the task draft",field("title").value==="整理两条周末散步路线");close();
  await open("散步路线");field("start-time").value="1";close();
  await open("散步路线");check("Partial time input survives closing and reopening",field("start-time").value==="1");overlay().querySelector(".tc-planner-te-discard").click();
  await open("街景照片");check("Due-only task keeps start empty",field("start-date").value===""&&field("end-date").value==="2099-01-10"&&field("end-time").value==="");
  field("title").value="选出八张街景照片";await save();
  check("Due-only save does not create start or time",(await task("街景照片")).rawText==="- [ ] 选出八张街景照片 [due:: 2099-01-10]");
  await open("街景照片");field("end-date").value="";await save();
  check("Date can be removed",!(await task("街景照片")).rawText.includes("due::"));
  await open("散步路线");field("title").value="不能覆盖外部改动";
  const changed=(await text()).replace("整理两条周末散步路线","本人在源笔记改了路线");await app.vault.modify(app.vault.getAbstractFileByPath(path),changed);
  overlay().querySelector(".tc-planner-te-btn--primary").click();await wait(()=>overlay()?.querySelector(".tc-planner-te-error")?.textContent);
  check("External edit is not overwritten and input is retained",(await text())===changed&&field("title").value==="不能覆盖外部改动");close();
  const raw=await task("本人在源笔记");
  const completed=await p.editTaskFields(raw,{status:"done"});
  check("Completion records actual date and preserves suffix",completed.rawText.includes("[completion:: "+p.getLocalYmd()+"] ^walk  "));
  const reopened=await p.editTaskFields({...raw,rawText:completed.rawText,text:completed.rawText},{status:"todo"});
  check("Reopen keeps original source and removes completion",reopened.rawText.startsWith("- [ ]")&&!reopened.rawText.includes("completion::"));
  const added=await p.appendTaskToProject({path,text:"试听一张新专辑"});
  check("Project append stays before next level-one heading",(await text()).indexOf("试听一张新专辑")<(await text()).indexOf("# 留下的记录"));
  check("Append returns the exact source line",(await text()).split("\n")[added.line]===added.rawText);
  const moc=fixture+"/项目.md",mocSource="---\ntest_fixture: true\n---\n\n## 项目\n\n[[任务]]\n";
  await app.vault.create(moc,mocSource);
  const routed=await p.appendTaskToProject({path:moc,candidatePaths:[path],text:"写下散步时发现的新想法"});
  check("A project entry routes to its existing task note",routed.path===path&&(await p.loadTextFromVault(moc))===mocSource);
  const beforeMove=await task("试听");await app.vault.modify(app.vault.getAbstractFileByPath(path),"A new opening\n"+await text());
  const moved=await p.editTaskFields(beforeMove,{title:"试听两张新专辑"});check("Task line movement is resolved",moved.line===beforeMove.line+1);
  await open("试听两张");
  const panel=overlay().querySelector(".tc-planner-te-panel");
  check("Editor contains only common fields",!panel.querySelector("#tc-planner-te-tags")&&!panel.querySelector(".tc-planner-te-section--repeat"));
  check("Editor fits current viewport",panel.getBoundingClientRect().right<=innerWidth&&panel.getBoundingClientRect().bottom<=innerHeight);
  fs.writeFileSync(root+"/fixture-after.md",await text());
  return {checks:report.length,passed:report.filter(r=>r.ok).length,fixture:path};
})()
